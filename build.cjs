const fs=require('fs'), path=require('path'), cp=require('child_process'), vm=require('vm');
require('./make-demo-avatars.cjs');
fs.mkdirSync('dist/assets',{recursive:true});
fs.cpSync('assets','dist/assets',{recursive:true});
cp.execFileSync(process.execPath,[require.resolve('tailwindcss/lib/cli.js'),'-i','styles.css','-o','dist/assets/app.css','--minify'],{stdio:'inherit'});
const cssDigest=require('crypto').createHash('sha256').update(fs.readFileSync('dist/assets/app.css')).digest('hex').slice(0,12);
const cssFile='app.'+cssDigest+'.css';
fs.renameSync('dist/assets/app.css','dist/assets/'+cssFile);
let html=fs.readFileSync('index.html','utf8');
html=html.replace(/<script src="https:\/\/cdn.tailwindcss.com"><\/script>/,'<link rel="stylesheet" href="assets/'+cssFile+'">');
html=html.replace(/<script src="https:\/\/unpkg.com\/vue@3\/dist\/vue.global.prod.js"><\/script>/,'<script src="assets/vue.global.prod.js"></script>');
html=html.replace(/<script>\s*tailwind.config[\s\S]*?<\/script>/,'');
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
for(const [,script] of scripts) new vm.Script(script);
fs.copyFileSync(require.resolve('vue/dist/vue.global.prod.js'),'dist/assets/vue.global.prod.js');
fs.writeFileSync('dist/index.html',html);
fs.mkdirSync('dist/classroom/assets',{recursive:true});
for(const file of [cssFile,'vue.global.prod.js']) fs.copyFileSync('dist/assets/'+file,'dist/classroom/assets/'+file);
const classroomHtml=html.replace('const DEMO_ENABLED = true;', 'const DEMO_ENABLED = false;');
if(classroomHtml===html) throw Error('Classroom build flag not replaced');
fs.writeFileSync('dist/classroom/index.html',classroomHtml);
fs.copyFileSync('_headers','dist/_headers');
console.log('Build complete: dist/');
